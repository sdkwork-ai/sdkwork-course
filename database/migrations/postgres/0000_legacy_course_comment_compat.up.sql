-- sdkwork:migration
-- id: 0000_legacy_course_comment_compat
-- engine: postgres
-- module: sdkwork-course
-- purpose: Keep fresh baseline installs compatible with the historical
--   0001_organization_id_not_null migration. That migration was authored
--   while course_comment still existed; the consolidated baseline and the
--   later 0003_drop_course_comment removed it. Fresh installs apply the
--   baseline followed by every ordered migration, so 0001 must still see the
--   legacy table once. Create a minimal placeholder only when 0003 has not
--   been applied; existing deployments (0003 already recorded) are untouched
--   and the later 0003 migration drops the placeholder on fresh installs.
-- reversible: false
-- rollback: forward-fix (this migration only restores temporary compatibility
--   for the historical 0001 migration and is a no-op after 0003)
-- transactional: true
-- lock: lightweight
-- lock_timeout: 2s
-- statement_timeout: 30s

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM ops_schema_migration_history
    WHERE module_id = 'course'
      AND version = '0003_drop_course_comment'
  ) AND to_regclass('course_comment') IS NULL THEN
    CREATE TABLE course_comment (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    );
  END IF;
END
$$;

COMMIT;
